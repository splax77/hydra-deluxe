"""Turn Clone Hero's section-name list into src/parse/section_names_table.cpp.

Usage: py -I tools/gen_section_names.py data/clone-hero-1.1.0.6142-section-names.tsv src/parse/section_names_table.cpp

The TSV holds one row per marker name: the name, a tab, the words Clone Hero
shows. Lines starting with '#' are comments. The output is a C++ array sorted
by key in byte order, which is what section_display_name's binary search
needs. tests/test_section_names.cpp checks the checked-in output still agrees
with the TSV, so rerun this after any change to the TSV.
"""

import sys


def read_rows(tsv_path):
    rows = []
    with open(tsv_path, "r", encoding="ascii", newline="") as f:
        for number, raw in enumerate(f, start=1):
            line = raw.rstrip("\r\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 2:
                sys.exit(f"{tsv_path} line {number}: expected 2 tab-separated fields, found {len(parts)}")
            rows.append((parts[0], parts[1]))
    keys = [k for k, _ in rows]
    if len(set(keys)) != len(keys):
        sys.exit(f"{tsv_path}: a marker name appears twice")
    return rows


def cpp_string(text):
    if any(c in text for c in '"\\') or any(not (" " <= c <= "~") for c in text):
        sys.exit(f"cannot write {text!r} as a plain C++ string literal")
    return f'"{text}"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tsv_path, out_path = sys.argv[1], sys.argv[2]
    rows = sorted(read_rows(tsv_path), key=lambda row: row[0].encode("ascii"))
    lines = [
        "// Generated by tools/gen_section_names.py from",
        "// data/clone-hero-1.1.0.6142-section-names.tsv. Do not edit; rerun the tool.",
        '#include "parse/section_names.h"',
        "",
        "namespace hydra {",
        "",
        "namespace {",
        "",
        "constexpr SectionNameRow kRows[] = {",
    ]
    lines += [f"    {{{cpp_string(k)}, {cpp_string(v)}}}," for k, v in rows]
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        "SectionNameTable section_name_table() {",
        "    return {kRows, sizeof(kRows) / sizeof(kRows[0])};",
        "}",
        "",
        "}  // namespace hydra",
        "",
    ]
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(rows)} rows to {out_path}")


if __name__ == "__main__":
    main()
